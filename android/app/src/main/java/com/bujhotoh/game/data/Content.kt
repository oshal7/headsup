package com.bujhotoh.game.data

import org.json.JSONArray
import org.json.JSONObject

/** How clue-givers should give clues. The hint text itself is a string resource (see ui/Text.kt). */
enum class ClueMode(val key: String) {
    SAY("say"), ACT("act"), HUM("hum"), SOUND("sound");

    companion object {
        fun from(key: String?): ClueMode = entries.firstOrNull { it.key == key } ?: SAY
    }
}

/** A card pack's origin. "world" = universal. */
data class Region(val id: String, val name: String, val flag: String) {
    val isWorld: Boolean get() = id == WORLD

    companion object { const val WORLD = "world" }
}

/** A home-screen shelf, e.g. "Party Classics". */
data class Group(val id: String, val name: String, val desc: String = "")

/**
 * A category such as Animals or Movies. Universal categories only have the "world" variant;
 * others have one card list per country (e.g. Movies: India, USA, UK, China).
 */
data class Category(
    val id: String,
    val name: String,
    val emoji: String,
    val colorStart: Int,
    val colorEnd: Int,
    val desc: String,
    val mode: ClueMode,
    /** region id -> cards, in the order regions are listed in the content file. */
    val variants: Map<String, List<String>>,
    /** Which [Group] (home-screen shelf) it belongs to. */
    val group: String = "",
) {
    val isUniversal: Boolean get() = variants.keys == setOf(Region.WORLD)
}

/** Something that can be played: one category + region, Mix, or a custom deck. */
data class Deck(
    val id: String,
    val name: String,
    val emoji: String,
    /** Gradient colours as ARGB ints. */
    val colorStart: Int,
    val colorEnd: Int,
    val desc: String,
    val mode: ClueMode,
    val words: List<String>,
    val region: Region? = null,
    val custom: Boolean = false,
    val mix: Boolean = false,
) {
    /** "Movies 🇺🇸" style title. */
    val title: String get() = if (region != null && !region.isWorld) "$name ${region.flag}" else name
}

/** One card shown during a round. [hint] is shown under the word (e.g. "Act it out"), [source] for Mix. */
data class Card(val text: String, val mode: ClueMode, val source: String = "")

data class Content(val regions: List<Region>, val categories: List<Category>, val groups: List<Group> = emptyList()) {
    /** Categories on a home-screen shelf, in content order. */
    fun categoriesIn(g: Group): List<Category> = categories.filter { it.group == g.id }

    fun region(id: String?): Region? = regions.firstOrNull { it.id == id }

    /** Regions this category can be played in, in content order. */
    fun regionsFor(c: Category): List<Region> = regions.filter { it.id in c.variants }

    /** Default region for a category: the player's last choice, then their home country, then World, then first. */
    fun defaultRegion(c: Category, home: String?, lastChoice: String?): Region {
        val options = regionsFor(c)
        return options.firstOrNull { it.id == lastChoice }
            ?: options.firstOrNull { it.id == home }
            ?: options.firstOrNull { it.isWorld }
            ?: options.first()
    }

    fun deckFor(c: Category, region: Region): Deck = Deck(
        id = "${c.id}:${region.id}",
        name = c.name, emoji = c.emoji, colorStart = c.colorStart, colorEnd = c.colorEnd,
        desc = c.desc, mode = c.mode, words = c.variants[region.id].orEmpty(), region = region,
    )

    /** Mix: every universal card plus the player's home-country packs. */
    fun mixDeck(home: String?, name: String, desc: String): Deck = Deck(
        id = "mix:${home ?: Region.WORLD}", name = name, emoji = "🌶️",
        colorStart = Decks.parseColor("#ff0844"), colorEnd = Decks.parseColor("#ffb199"),
        desc = desc, mode = ClueMode.SAY, words = mixCards(home).map { it.text }, mix = true,
    )

    fun mixCards(home: String?): List<Card> = categories.flatMap { c ->
        listOfNotNull(c.variants[Region.WORLD]?.let { region(Region.WORLD) }, home?.takeIf { it != Region.WORLD }?.let { h ->
            c.variants[h]?.let { region(h) }
        }).flatMap { r -> c.variants[r.id].orEmpty().map { Card(it, c.mode, c.name + if (r.isWorld) "" else " ${r.flag}") } }
    }.distinctBy { it.text }

    /** Cards for a deck. */
    fun cardsFor(d: Deck, home: String?): List<Card> =
        if (d.mix) mixCards(home) else d.words.map { Card(it, d.mode) }

    companion object {
        /** Parses assets/content.json (generated by tools/build-content.js). */
        fun parse(json: String): Content {
            val root = JSONObject(json)
            val regions = root.getJSONArray("regions").let { a ->
                (0 until a.length()).map { i -> a.getJSONObject(i).let { Region(it.getString("id"), it.getString("name"), it.getString("flag")) } }
            }
            val cats = root.getJSONArray("categories").let { a ->
                (0 until a.length()).map { i ->
                    val o = a.getJSONObject(i)
                    val colors = o.getJSONArray("colors")
                    val v = o.getJSONObject("variants")
                    val variants = linkedMapOf<String, List<String>>()
                    regions.forEach { r -> if (v.has(r.id)) variants[r.id] = v.getJSONArray(r.id).strings() }
                    Category(
                        id = o.getString("id"), name = o.getString("name"), emoji = o.getString("emoji"),
                        colorStart = Decks.parseColor(colors.getString(0)), colorEnd = Decks.parseColor(colors.getString(1)),
                        desc = o.optString("desc"), mode = ClueMode.from(o.optString("mode")), variants = variants,
                        group = o.optString("group"),
                    )
                }
            }
            val groups = root.optJSONArray("groups")?.let { a ->
                (0 until a.length()).map { i -> a.getJSONObject(i).let { Group(it.getString("id"), it.getString("name"), it.optString("desc")) } }
            }.orEmpty()
            return Content(regions, cats, groups)
        }
    }
}

private fun JSONArray.strings() = (0 until length()).map { getString(it) }.distinct()

/** Custom ("make your own") decks and colour helpers. */
object Decks {
    fun customToJson(decks: List<Deck>): String = JSONArray().apply {
        decks.forEach { d ->
            put(JSONObject().apply {
                put("id", d.id); put("name", d.name); put("emoji", d.emoji)
                put("colors", JSONArray().put(toHex(d.colorStart)).put(toHex(d.colorEnd)))
                put("mode", d.mode.key); put("desc", d.desc)
                put("words", JSONArray(d.words))
            })
        }
    }.toString()

    fun customFromJson(json: String?): List<Deck> {
        if (json.isNullOrBlank()) return emptyList()
        return runCatching {
            val arr = JSONArray(json)
            (0 until arr.length()).map { i ->
                val o = arr.getJSONObject(i)
                val colors = o.getJSONArray("colors")
                Deck(
                    id = o.getString("id"), name = o.getString("name"), emoji = o.optString("emoji", "🎉"),
                    colorStart = parseColor(colors.getString(0)), colorEnd = parseColor(colors.getString(1)),
                    desc = o.optString("desc", ""), mode = ClueMode.from(o.optString("mode")),
                    words = o.getJSONArray("words").strings(), custom = true,
                )
            }
        }.getOrDefault(emptyList())
    }

    /** "#rrggbb" -> opaque ARGB int (pure Kotlin so it works in unit tests). */
    fun parseColor(hex: String): Int = (0xFF000000L or hex.removePrefix("#").toLong(16)).toInt()

    private fun toHex(argb: Int) = "#%06x".format(argb and 0xFFFFFF)

    val CUSTOM_PALETTES = listOf(
        "#ee0979" to "#ff6a00", "#4776e6" to "#8e54e9", "#00c6ff" to "#0072ff",
        "#f7797d" to "#fbd786", "#43cea2" to "#185a9d",
    )
    val CUSTOM_EMOJIS = listOf("🎉", "👨‍👩‍👧", "🏢", "🎓", "🏖️", "🐶", "🍕", "💃", "🤪", "❤️", "🎮", "🏠")
}
